export function obterAssetDoManifesto({
  temaId,
  categoria,
  assetId,
}) {
  const tema =
    String(temaId || "")
      .normalize("NFD")
      .replace(/[\u0300-\u036f]/g, "")
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-+|-+$/g, "");

  const grupo =
    String(categoria || "")
      .normalize("NFD")
      .replace(/[\u0300-\u036f]/g, "")
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-+|-+$/g, "");

  const asset =
    String(assetId || "")
      .normalize("NFD")
      .replace(/[\u0300-\u036f]/g, "")
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-+|-+$/g, "");

  return (
    MANIFEST_PACKS_VISUAIS?.[tema]
      ?.[grupo]?.[asset] ||
    ""
  );
}

